-- Modelo H2 de referência. NÃO é executado automaticamente.
-- Hibernate gera o esquema a partir das entidades JPA.
CREATE TABLE usuarios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(80) NOT NULL,
    apelido VARCHAR(30) NOT NULL UNIQUE,
    email VARCHAR(120) NOT NULL UNIQUE,
    bio VARCHAR(300),
    data_cadastro DATE NOT NULL
);
CREATE TABLE generos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(40) NOT NULL UNIQUE
);
CREATE TABLE filmes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo VARCHAR(140) NOT NULL,
    diretor VARCHAR(100) NOT NULL,
    ano_lancamento INTEGER NOT NULL,
    duracao_minutos INTEGER NOT NULL,
    sinopse VARCHAR(2000) NOT NULL,
    capa VARCHAR(20) NOT NULL
);
CREATE TABLE filme_genero (
    filme_id BIGINT NOT NULL,
    genero_id BIGINT NOT NULL,
    PRIMARY KEY (filme_id, genero_id),
    FOREIGN KEY (filme_id) REFERENCES filmes(id),
    FOREIGN KEY (genero_id) REFERENCES generos(id)
);
CREATE TABLE avaliacoes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id BIGINT NOT NULL,
    filme_id BIGINT NOT NULL,
    nota DECIMAL(2,1) NOT NULL,
    comentario VARCHAR(3000),
    data_assistido DATE NOT NULL,
    favorito BOOLEAN NOT NULL,
    spoiler BOOLEAN NOT NULL,
    UNIQUE (usuario_id, filme_id),
    FOREIGN KEY (usuario_id) REFERENCES usuarios(id),
    FOREIGN KEY (filme_id) REFERENCES filmes(id)
);
CREATE TABLE listas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id BIGINT NOT NULL,
    nome VARCHAR(100) NOT NULL,
    descricao VARCHAR(1000),
    FOREIGN KEY (usuario_id) REFERENCES usuarios(id)
);
CREATE TABLE itens_lista (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lista_id BIGINT NOT NULL,
    filme_id BIGINT NOT NULL,
    posicao INTEGER NOT NULL,
    observacao VARCHAR(300),
    UNIQUE (lista_id, filme_id),
    FOREIGN KEY (lista_id) REFERENCES listas(id),
    FOREIGN KEY (filme_id) REFERENCES filmes(id)
);
-- Intervalos, datas, pelo menos um gênero e meia estrela são validados
-- pelos Form DTOs/Services. As cascatas de exclusão da lista são feitas
-- pelo JPA (orphanRemoval/CascadeType.ALL), não por ON DELETE CASCADE.
